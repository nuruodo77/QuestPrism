test("loading a built-in preset applies its rows and becomes the active preset", function()
    QuestPrism.Settings.SetAccountWide(false)
    QuestPrism.Settings.Reset()
    QuestPrism.Settings.LoadPreset("Leveling")
    assertEq(QuestPrism.Settings.Get("Campaign"), true); assertEq(QuestPrism.Settings.Get("Important"), true)
    assertEq(QuestPrism.Settings.Get("LocalStory"), true)
    assertEq(QuestPrism.Settings.Get("Legendary"), false); assertEq(QuestPrism.Settings.Get("Meta"), false)
    assertEq(QuestPrism.Settings.Get("Repeatable"), false); assertEq(QuestPrism.Settings.Get("Expedition"), false)
    assertEq(QuestPrism.Settings.Get("Trivial"), false)
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), true, "world quests blocked by Leveling")
    assertEq(QuestPrism.Settings.GetActivePresetName(), "Leveling")
    QuestPrism.Settings.LoadPreset("Weekly chores")
    assertEq(QuestPrism.Settings.Get("Campaign"), false); assertEq(QuestPrism.Settings.Get("Meta"), true)
    assertEq(QuestPrism.Settings.Get("Repeatable"), true); assertEq(QuestPrism.Settings.Get("Expedition"), true)
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), false, "world quests shown by Weekly chores")
    QuestPrism.Settings.LoadPreset("Endgame")
    assertEq(QuestPrism.Settings.Get("LocalStory"), false); assertEq(QuestPrism.Settings.Get("Legendary"), true)
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), false)
    QuestPrism.Settings.LoadPreset("Campaign only")
    assertEq(QuestPrism.Settings.Get("Legendary"), true); assertEq(QuestPrism.Settings.Get("LocalStory"), false)
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), true)
    local snapshot = QuestPrism.Settings.GetPresetSnapshot("Leveling")
    assertEq(snapshot.Campaign, true); assertEq(snapshot.HideWorldQuests, true)
    assertEq(QuestPrism.Settings.GetPresetSnapshot("Nope"), nil)
end)

test("built-in presets cannot be overwritten or deleted", function()
    assertFalse(QuestPrism.Settings.SavePreset("Leveling"), "save refused")
    assertFalse(QuestPrism.Settings.SavePreset("leveling"), "save refused, case-insensitive")
    assertEq(QuestPrismDB.presets and QuestPrismDB.presets.Leveling, nil, "nothing stored")
    QuestPrism.Settings.DeletePreset("Leveling")
    assertTrue(QuestPrism.Settings.IsBuiltInPreset("Leveling"), "still there")
    assertTrue(QuestPrism.Settings.SavePreset("Mine"), "saving a normal name works")
    assertEq(QuestPrism.Settings.GetActivePresetName(), "Mine", "saving selects the preset")
    QuestPrism.Settings.DeletePreset("Mine")
    assertEq(QuestPrism.Settings.GetActivePresetName(), nil, "deleting the active preset clears it")
end)

test("editing a row keeps the active preset and flags it as modified", function()
    QuestPrism.Settings.LoadPreset("Leveling")
    assertFalse(QuestPrism.Settings.IsActivePresetModified())
    QuestPrism.Settings.Set("Meta", true)
    assertEq(QuestPrism.Settings.GetActivePresetName(), "Leveling", "still the active preset")
    assertTrue(QuestPrism.Settings.IsActivePresetModified())
    QuestPrism.Settings.Set("Meta", false)
    assertFalse(QuestPrism.Settings.IsActivePresetModified(), "back to the preset")
    QuestPrism.Settings.Set("HideWorldQuests", false)
    assertTrue(QuestPrism.Settings.IsActivePresetModified(), "the world quest row counts")
    QuestPrism.Settings.Reset()
    assertFalse(QuestPrism.Settings.IsActivePresetModified(), "no active preset, never modified")
end)

