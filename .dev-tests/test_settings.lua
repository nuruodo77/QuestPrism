test("filters are per character by default", function()
    QuestPrism.Settings.Set("Campaign", false)
    assertEq(QuestPrismCharDB.Campaign, false)
    assertEq(QuestPrism.Settings.IsAccountWide(), false)
end)

test("enabling account-wide seeds the account table from this character", function()
    QuestPrismCharDB.Campaign = false
    QuestPrismCharDB.HideWorldQuests = true
    QuestPrism.Settings.SetAccountWide(true)
    assertEq(QuestPrism.Settings.IsAccountWide(), true)
    assertEq(QuestPrismDB.filters.Campaign, false, "seeded Campaign")
    assertEq(QuestPrismDB.filters.HideWorldQuests, true, "seeded world quest block")
    QuestPrism.Settings.Set("HideWorldQuests", false)
    assertEq(QuestPrism.Settings.Get("Campaign"), false)
end)

test("account-wide reads and writes go to the account table", function()
    QuestPrism.Settings.SetAccountWide(true)
    QuestPrism.Settings.Set("Legendary", false)
    assertEq(QuestPrismDB.filters.Legendary, false)
    assertEq(QuestPrismCharDB.Legendary, true, "character value untouched")
    assertEq(QuestPrism.Settings.Get("Legendary"), false)
end)

test("non-filter keys stay per character even when account-wide", function()
    QuestPrism.Settings.SetAccountWide(true)
    QuestPrism.Settings.Set("debug", true)
    assertEq(QuestPrismCharDB.debug, true)
    assertEq(QuestPrismDB.filters.debug, nil)
    QuestPrism.Settings.Set("debug", false)
end)

test("disabling account-wide falls back to character values", function()
    QuestPrism.Settings.SetAccountWide(true)
    QuestPrism.Settings.Set("Meta", false)
    QuestPrism.Settings.SetAccountWide(false)
    assertEq(QuestPrism.Settings.Get("Meta"), true)
end)

test("presets and Reset honor the active scope", function()
    QuestPrism.Settings.SetAccountWide(true)
    QuestPrism.Settings.Set("Important", false)
    QuestPrism.Settings.SavePreset("acct")
