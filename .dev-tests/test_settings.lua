test("built-in presets are listed in a fixed order and recognised by name", function()
    local names = QuestPrism.Settings.ListBuiltInPresetNames()
    assertEq(#names, 4)
    assertEq(names[1], "Leveling"); assertEq(names[2], "Campaign only")
    assertEq(names[3], "Endgame"); assertEq(names[4], "Weekly chores")
    assertTrue(QuestPrism.Settings.IsBuiltInPreset("Leveling"))
    assertFalse(QuestPrism.Settings.IsBuiltInPreset("Mine"))
