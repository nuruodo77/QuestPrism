test("HideWorldQuests defaults off, is saved in presets, and Reset lifts it", function()
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), false)
    QuestPrism.Settings.Set("HideWorldQuests", true)
    QuestPrism.Settings.SavePreset("Blocked")
    assertEq(QuestPrismDB.presets.Blocked.HideWorldQuests, true, "in the preset")
    QuestPrism.Settings.Reset()
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), false, "Show all lifts the block")
    QuestPrism.Settings.LoadPreset("Blocked")
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), true, "restored by the preset")
    QuestPrism.Settings.Set("HideWorldQuests", false)
    QuestPrism.Settings.DeletePreset("Blocked")
end)

test("Initialize drops the retired HideWarbandCompleted keys from every store", function()
    QuestPrismCharDB = { HideWarbandCompleted_Meta = true, Campaign = false }
    QuestPrismDB = { filters = { HideWarbandCompleted_Campaign = false }, presets = { Old = { Meta = true, HideWarbandCompleted_Meta = true } } }
    QuestPrism.Settings.Initialize()
    assertEq(QuestPrismCharDB.HideWarbandCompleted_Meta, nil, "char store")
    assertEq(QuestPrismCharDB.Campaign, false, "other keys untouched")
    assertEq(QuestPrismDB.filters.HideWarbandCompleted_Campaign, nil, "account store")
    assertEq(QuestPrismDB.presets.Old.HideWarbandCompleted_Meta, nil, "preset")
    assertEq(QuestPrismDB.presets.Old.Meta, true, "preset keeps its toggles")
    QuestPrismDB.presets = nil
end)

test("Solo shows only one type and a second Solo restores the previous filters", function()
    QuestPrism.Settings.Reset()
    QuestPrism.Settings.Set("Meta", false); QuestPrism.Settings.Set("Trivial", false)
    QuestPrism.Settings.Solo("Campaign")
    assertTrue(QuestPrism.Settings.IsSoloed("Campaign"))
    assertEq(QuestPrism.Settings.Get("Campaign"), true)
    for _, k in ipairs({ "Important", "Legendary", "Meta", "Repeatable", "LocalStory", "Expedition", "Trivial" }) do
        assertEq(QuestPrism.Settings.Get(k), false, k .. " should be hidden while soloed")
    end
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), true, "world quests hidden while soloed")
    QuestPrism.Settings.Solo("Campaign")
    assertFalse(QuestPrism.Settings.IsSoloed("Campaign"))
    assertEq(QuestPrism.Settings.Get("Meta"), false, "restored Meta")
    assertEq(QuestPrism.Settings.Get("Important"), true, "restored Important")
    assertEq(QuestPrism.Settings.Get("Trivial"), false, "restored Trivial")
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), false, "restored world quests")
end)

test("HideAll clears every row including World Quests; Reset brings them all back", function()
    QuestPrism.Settings.Reset()
    QuestPrism.Settings.HideAll()
    for _, k in ipairs({ "Campaign", "Important", "Legendary", "Meta", "Repeatable", "LocalStory", "Expedition", "Trivial" }) do
        assertEq(QuestPrism.Settings.Get(k), false, k)
    end
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), true, "world quests hidden too")
    QuestPrism.Settings.Reset()
    assertEq(QuestPrism.Settings.Get("HideWorldQuests"), false)
end)

test("Initialize renames saved presets that share a built-in's name", function()
    QuestPrismCharDB = { activePreset = "endgame" }
    QuestPrismDB = { presets = { endgame = { Campaign = false }, Mine = { Meta = false }, ["Leveling (yours)"] = { Meta = true }, Leveling = { Meta = false } } }
    QuestPrism.Settings.Initialize()
    assertEq(QuestPrismDB.presets.endgame, nil, "shadowed name gone")
    assertEq(QuestPrismDB.presets["endgame (yours)"].Campaign, false, "kept under the new name")
    assertEq(QuestPrismDB.presets.Mine.Meta, false, "others untouched")
    assertEq(QuestPrismDB.presets.Leveling, nil)
    assertEq(QuestPrismDB.presets["Leveling (yours) (yours)"].Meta, false, "suffix repeated when taken")
    assertEq(QuestPrismCharDB.activePreset, "endgame (yours)", "active preset follows the rename")
    assertEq(QuestPrism.Settings.GetActivePresetName(), "endgame (yours)")
    QuestPrismDB.presets = nil
end)

test("Solo on a different type while soloed switches without losing the snapshot", function()
    QuestPrism.Settings.Reset(); QuestPrism.Settings.Set("Meta", false)
    QuestPrism.Settings.Solo("Campaign"); QuestPrism.Settings.Solo("Legendary")
    assertTrue(QuestPrism.Settings.IsSoloed("Legendary")); assertEq(QuestPrism.Settings.Get("Campaign"), false)
    QuestPrism.Settings.Solo("Legendary")
    assertEq(QuestPrism.Settings.Get("Meta"), false, "snapshot kept"); assertEq(QuestPrism.Settings.Get("Campaign"), true)
end)

test("a manual change while soloed ends solo mode without restoring", function()
